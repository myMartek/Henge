#!/bin/bash
# visionOS spike: cross-compiles what the engine's network needs (libffi, glib with
# its pcre2 and libintl, libslirp) for Apple Vision Pro or its simulator.
# Same pins and the same Meson cross-file shape as Husk's scripts/build_ios.sh,
# with the visionOS target triple.
#
# Usage: xros/scripts/build_deps_xros.sh [xros|xrsimulator]     (default: xros)
# Output: xros/deps/<platform>/{lib,include}
# Needs: meson and ninja on PATH (MESON=/path/to/meson to pick one).
set -uo pipefail

PLATFORM="${1:-xros}"
case "$PLATFORM" in
    xros)        TRIPLE_SUFFIX="" ;;
    xrsimulator) TRIPLE_SUFFIX="-simulator" ;;
    *) echo "usage: $0 [xros|xrsimulator]" >&2; exit 2 ;;
esac

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
DL="$ROOT/xros/deps-src/downloads"
SRC="$ROOT/xros/deps-src/$PLATFORM"
PREFIX="$ROOT/xros/deps/$PLATFORM"
LOGS="$ROOT/xros/deps-src/logs/$PLATFORM"
mkdir -p "$DL" "$SRC" "$PREFIX" "$LOGS"

MESON="${MESON:-meson}"
MINVER="${XROS_MINVER:-2.0}"
ARCH=arm64
NCPU="$(sysctl -n hw.ncpu)"
SDKROOT="$(xcrun --sdk "$PLATFORM" --show-sdk-path)"
TARGET="-target $ARCH-apple-xros$MINVER$TRIPLE_SUFFIX"

FFI_SRC="https://github.com/libffi/libffi/releases/download/v3.5.0/libffi-3.5.0.tar.gz"
GLIB_SRC="https://download.gnome.org/sources/glib/2.83/glib-2.83.0.tar.xz"
SLIRP_SRC="https://github.com/utmapp/libslirp/releases/download/v4.9.1-release-mirror/libslirp-v4.9.1.tar.gz"

export CC="$(xcrun --sdk "$PLATFORM" --find clang) $TARGET"
export CXX="$(xcrun --sdk "$PLATFORM" --find clang++) $TARGET"
export OBJCC="$(xcrun --sdk "$PLATFORM" --find clang)"
export AR="$(xcrun --sdk "$PLATFORM" --find ar)"
export NM="$(xcrun --sdk "$PLATFORM" --find nm)"
export RANLIB="$(xcrun --sdk "$PLATFORM" --find ranlib)"
export STRIP="$(xcrun --sdk "$PLATFORM" --find strip)"
export LD="$(xcrun --sdk "$PLATFORM" --find ld)"
export CFLAGS="-arch $ARCH -isysroot $SDKROOT -I$PREFIX/include $TARGET -O2"
export CXXFLAGS="$CFLAGS"
export CPPFLAGS="-arch $ARCH -isysroot $SDKROOT -I$PREFIX/include $TARGET"
export OBJCFLAGS="$CFLAGS"
export LDFLAGS="-arch $ARCH -isysroot $SDKROOT -L$PREFIX/lib $TARGET"
# Only this prefix: a Homebrew library for the Mac must never reach a visionOS link.
export PKG_CONFIG="$(command -v pkg-config)"
export PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig:$PREFIX/share/pkgconfig"
unset PKG_CONFIG_PATH

fail() { echo "[FAIL] $1 (see $2)" >&2; exit 1; }

fetch() { # url -> unpacked under $SRC
    local url="$1" file="$DL/$(basename "$1")"
    if [ ! -s "$file" ]; then
        echo "[get ] $(basename "$file")"
        curl -fL --retry 3 --retry-delay 5 -o "$file.part" "$url" || fail "download $url" "-"
        mv "$file.part" "$file"
    fi
    local stamp="$SRC/.unpacked-$(basename "$file")"
    [ -f "$stamp" ] || { tar -xf "$file" -C "$SRC" && touch "$stamp"; } || fail "unpack $file" "-"
}

meson_quote() { echo "'$(echo $* | sed "s/ /','/g")'"; }

gen_cross() { # file system
    cat > "$1" <<EOF
# Generated by xros/scripts/build_deps_xros.sh
[properties]
needs_exe_wrapper = true
[built-in options]
c_args = [$(meson_quote $CFLAGS)]
cpp_args = [$(meson_quote $CXXFLAGS)]
objc_args = [$(meson_quote $OBJCFLAGS $TARGET)]
objcpp_args = [$(meson_quote $OBJCFLAGS $TARGET)]
c_link_args = [$(meson_quote $LDFLAGS)]
cpp_link_args = [$(meson_quote $LDFLAGS)]
objc_link_args = [$(meson_quote $LDFLAGS)]
objcpp_link_args = [$(meson_quote $LDFLAGS)]
[binaries]
c = [$(meson_quote $CC)]
cpp = [$(meson_quote $CXX)]
objc = [$(meson_quote $OBJCC)]
objcpp = [$(meson_quote $OBJCC)]
ar = ['$AR']
nm = ['$NM']
ranlib = ['$RANLIB']
strip = ['$STRIP', '-x']
pkg-config = ['$PKG_CONFIG']
[host_machine]
system = '$2'
cpu_family = 'aarch64'
cpu = 'aarch64'
endian = 'little'
EOF
}
CROSS_IOS="$SRC/cross-ios.meson"       # glib: "ios" keeps Cocoa and Carbon out
CROSS_DARWIN="$SRC/cross-darwin.meson" # libslirp: wants darwin for libresolv
gen_cross "$CROSS_IOS" ios
gen_cross "$CROSS_DARWIN" darwin

build_autotools() { # dir configure-args...
    local name="$1"; shift
    local log="$LOGS/$name.log"
    [ -f "$SRC/.built-$name" ] && { echo "[skip] $name"; return 0; }
    echo "[make] $name"
    ( cd "$SRC/$name" \
      && ./configure --host=aarch64-apple-darwin --prefix="$PREFIX" --enable-static --disable-shared "$@" \
      && make -j"$NCPU" && make install ) > "$log" 2>&1 || fail "$name" "$log"
    touch "$SRC/.built-$name"
}

build_meson() { # dir cross meson-args...
    local name="$1" cross="$2"; shift 2
    local log="$LOGS/$name.log"
    [ -f "$SRC/.built-$name" ] && { echo "[skip] $name"; return 0; }
    echo "[meson] $name"
    rm -rf "$SRC/$name/_xros_build"
    ( cd "$SRC/$name" \
      && "$MESON" setup _xros_build --cross-file "$cross" --prefix="$PREFIX" --libdir=lib \
                --buildtype=release --default-library=static "$@" \
      && "$MESON" compile -C _xros_build -j "$NCPU" \
      && "$MESON" install -C _xros_build ) > "$log" 2>&1 || fail "$name" "$log"
    touch "$SRC/.built-$name"
}

echo "visionOS deps: platform=$PLATFORM min=$MINVER sdk=$SDKROOT"
fetch "$FFI_SRC"; fetch "$GLIB_SRC"; fetch "$SLIRP_SRC"

build_autotools libffi-3.5.0
build_meson glib-2.83.0 "$CROSS_IOS" \
    -Dtests=false -Dnls=disabled -Dintrospection=disabled -Dselinux=disabled -Dlibmount=disabled \
    -Ddtrace=disabled -Dman-pages=disabled -Dglib_debug=disabled -Dxattr=false
# libslirp looks for libresolv only when the system is "darwin"; no patch needed with the darwin cross file.
build_meson libslirp-v4.9.1 "$CROSS_DARWIN"

# glib builds pcre2 and libintl as subprojects when the prefix has none: put them beside the rest.
for l in libpcre2-8 libintl; do
    [ -f "$PREFIX/lib/$l.a" ] && continue
    found="$(find "$SRC/glib-2.83.0/_xros_build/subprojects" -name "$l.a" 2>/dev/null | head -1)"
    [ -n "$found" ] && cp "$found" "$PREFIX/lib/"
done
echo "--- $PREFIX/lib"
ls -la "$PREFIX/lib"/*.a
